<?php
/**
 * Прогон всех проверок интеграции VL Account × Simla.com.
 *
 * Запуск: php tests/run.php
 *
 * WordPress не нужен: тесты работают на заглушках из bootstrap.php и проверяют
 * логику связки — разбор ответов CRM, выбор источника баланса, расчёт списания
 * баллов, подготовку данных покупателя и вывод шаблонов во всех состояниях.
 */

$files = array(
	'test.php'           => 'Данные лояльности, покупатель, промокоды',
	'test-cart.php'      => 'Списание баллов в корзине',
	'test-templates.php' => 'Шаблоны кабинета и корзины',
);

$failed = 0;

foreach ( $files as $file => $title ) {
	echo "\n============================================================\n";
	echo "  $title  ($file)\n";
	echo "============================================================\n";

	$output = array();
	$code   = 0;

	exec( escapeshellcmd( PHP_BINARY ) . ' ' . escapeshellarg( __DIR__ . '/' . $file ) . ' 2>&1', $output, $code );

	echo implode( "\n", $output ) . "\n";

	if ( 0 !== $code ) {
		++$failed;
	}
}

echo "\n============================================================\n";
echo 0 === $failed ? "  ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ\n" : "  ПРОВАЛЕНО НАБОРОВ: $failed\n";
echo "============================================================\n";

exit( $failed > 0 ? 1 : 0 );
